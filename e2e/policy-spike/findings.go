//go:build spike && windows

package policyspike

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"testing"
)

// Finding is one mechanism × variant row for docs/policy-spike-findings.md.
type Finding struct {
	Mechanism       string `json:"mechanism"`
	Variant         string `json:"variant"`
	Works           string `json:"works"` // yes / no / partial
	Latency         string `json:"latency"`
	NeedsRelogon    string `json:"needs_relogon"`
	NeedsReboot     string `json:"needs_reboot"`
	VisibleGpresult string `json:"visible_gpresult"`
	Gotchas         string `json:"gotchas"`
	ClientSKUNote   string `json:"client_sku_note"`
}

var (
	findingsMu sync.Mutex
	findings   []Finding
)

func recordFinding(f Finding) {
	findingsMu.Lock()
	defer findingsMu.Unlock()
	findings = append(findings, f)
}

func writeFindingsArtifacts(t testing.TB) {
	t.Helper()
	findingsMu.Lock()
	rows := append([]Finding(nil), findings...)
	findingsMu.Unlock()

	sort.Slice(rows, func(i, j int) bool {
		if rows[i].Mechanism != rows[j].Mechanism {
			return rows[i].Mechanism < rows[j].Mechanism
		}
		return rows[i].Variant < rows[j].Variant
	})

	dir := os.Getenv("POLICY_SPIKE_OUT")
	if dir == "" {
		dir = "."
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatalf("mkdir findings out: %v", err)
	}

	jsonPath := filepath.Join(dir, "policy-spike-findings.json")
	b, err := json.MarshalIndent(rows, "", "  ")
	if err != nil {
		t.Fatalf("marshal findings: %v", err)
	}
	if err := os.WriteFile(jsonPath, b, 0o644); err != nil {
		t.Fatalf("write %s: %v", jsonPath, err)
	}

	mdPath := filepath.Join(dir, "policy-spike-findings.generated.md")
	if err := os.WriteFile(mdPath, []byte(renderFindingsMarkdown(rows)), 0o644); err != nil {
		t.Fatalf("write %s: %v", mdPath, err)
	}
	t.Logf("FINDINGS_JSON=%s", jsonPath)
	t.Logf("FINDINGS_MD=%s", mdPath)
	for _, r := range rows {
		t.Logf("FINDING|%s|%s|%s|%s|%s|%s|%s|%s|%s",
			r.Mechanism, r.Variant, r.Works, r.Latency, r.NeedsRelogon, r.NeedsReboot,
			r.VisibleGpresult, sanitizePipe(r.Gotchas), sanitizePipe(r.ClientSKUNote))
	}
}

func sanitizePipe(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", "/"), "\n", " ")
}

func renderFindingsMarkdown(rows []Finding) string {
	var b strings.Builder
	b.WriteString("# Policy spike findings (T-24)\n\n")
	b.WriteString("Facts observed on GitHub-hosted `windows-2025` (Windows Server 2025).\n")
	b.WriteString("Generated by `go test -tags=spike ./e2e/policy-spike/...`.\n")
	b.WriteString("Client SKU (Win11 Pro/Home) differences are noted only when known or strongly suspected; those SKUs are out of scope for this spike.\n\n")
	b.WriteString("| Mechanism | Variant | Works | Latency | Needs re-logon | Needs reboot | Visible in gpresult | Gotchas | Client SKU caveats |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
			escMD(r.Mechanism), escMD(r.Variant), escMD(r.Works), escMD(r.Latency),
			escMD(r.NeedsRelogon), escMD(r.NeedsReboot), escMD(r.VisibleGpresult),
			escMD(r.Gotchas), escMD(r.ClientSKUNote))
	}
	b.WriteString("\n## Notes\n\n")
	b.WriteString("- Latency is wall-clock from apply/refresh start to first successful verification of the effect.\n")
	b.WriteString("- \"Works\" means the spike observed the intended enforcement or registry effect on this Server SKU.\n")
	b.WriteString("- Forced logoff of an active session is not performed by Windows for logon-hours on a standalone box; the agent must call WTS APIs itself (see session-kick rows).\n")
	return b.String()
}

func escMD(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}
